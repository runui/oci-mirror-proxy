import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function renderFormula(tag, checksums) {
  if (!/^v\d+\.\d+\.\d+$/.test(tag) || tag !== tag.trim()) {
    throw new Error('Homebrew requires a stable release tag (vMAJOR.MINOR.PATCH).');
  }

  const sums = new Map();
  for (const line of checksums.trim().split(/\r?\n/)) {
    const match = /^([a-fA-F0-9]{64})\s+\*?(\S+)$/.exec(line);
    if (!match) throw new Error(`Invalid SHA256SUMS entry: ${line}`);
    if (sums.has(match[2])) throw new Error(`Duplicate checksum: ${match[2]}`);
    sums.set(match[2], match[1].toLowerCase());
  }

  function archive(os, arch) {
    const name = `oci-mirror-proxy_${tag}_${os}_${arch}.tar.gz`;
    const sum = sums.get(name);
    if (!sum) throw new Error(`Missing checksum: ${name}`);
    return `      url "https://github.com/runui/oci-mirror-proxy/releases/download/${tag}/${name}"
      sha256 "${sum}"`;
  }

  return `# Generated by scripts/update-homebrew.mjs from release SHA256SUMS.
class OciMirrorProxy < Formula
  desc "Local, read-only registry mirror proxy for Docker"
  homepage "https://ocimp.zmide.com"
  version "${tag.slice(1)}"

  on_macos do
    on_arm do
${archive('darwin', 'arm64')}
    end
    on_intel do
${archive('darwin', 'amd64')}
    end
  end

  on_linux do
    on_arm do
${archive('linux', 'arm64')}
    end
    on_intel do
${archive('linux', 'amd64')}
    end
  end

  def install
    bin.install "oci-mirror-proxy"
    pkgshare.install "config.example.yaml"
  end

  def caveats
    <<~EOS
      Before the first start, create your user configuration if it does not exist:
        oci-mirror-proxy init

      Run as your current user (without sudo):
        brew services start runui/oci-mirror-proxy/oci-mirror-proxy

      Docker settings are not changed automatically. See:
        https://ocimp.zmide.com/docs/installation#homebrew
    EOS
  end

  service do
    run [opt_bin/"oci-mirror-proxy", "serve"]
    keep_alive true
    log_path var/"log/oci-mirror-proxy.log"
    error_log_path var/"log/oci-mirror-proxy.log"
  end

  test do
    assert_equal "v#{version}", shell_output("#{bin}/oci-mirror-proxy version").strip
    config = testpath/"config.yaml"
    system bin/"oci-mirror-proxy", "init", "--config", config
    assert_path_exists config
    assert_match "listen:", config.read
  end
end
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [tag, checksumsPath, outputPath, ...extra] = process.argv.slice(2);
  if (!tag || !checksumsPath || !outputPath || extra.length > 0) {
    console.error('Usage: node scripts/update-homebrew.mjs <tag> <SHA256SUMS> <formula.rb>');
    process.exitCode = 1;
  } else {
    const formula = renderFormula(tag, await readFile(checksumsPath, 'utf8'));
    await writeFile(outputPath, formula);
  }
}
